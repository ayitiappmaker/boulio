const listeners = new Set<(language: LanguageCode) => void>();

export function getLanguage(): LanguageCode {
  const storedLanguage = readLanguageFromStorage();
  if (storedLanguage) {
    currentLanguage = storedLanguage;
  }

  return currentLanguage;
}

export function setLanguage(language: LanguageCode) {
  currentLanguage = language;
  writeLanguageToStorage(language);

  for (const listener of listeners) {
    listener(language);
  }
}

export function subscribeToLanguageChange(onChange: (language: LanguageCode) => void) {
  listeners.add(onChange);
  onChange(getLanguage());

  return () => {
    listeners.delete(onChange);
  };
}

export function useLanguage() {
  const [language, setLanguageState] = useState<LanguageCode>(() => getLanguage());

  useEffect(() => {
    const unsubscribe = subscribeToLanguageChange(setLanguageState);
    return unsubscribe;
  }, []);

  return language;
}

export function t(key: TranslationKey, values?: Record<string, string | number>) {
  const language = getLanguage();
  const dictionary = translations[language] ?? translations.en;
  const fallback = translations.en[key] ?? String(key);
  const raw = dictionary[key] ?? fallback;

  if (!values) {
    return raw;
  }

  return raw.replace(/\{\{(\w+)\}\}/g, (_, token: string) => {
    const value = values[token];
    return value === undefined ? '' : String(value);
  });
}

function readLanguageFromStorage(): LanguageCode | null {
  if (typeof localStorage === 'undefined') {
    return null;
  }

  try {
    const value = localStorage.getItem(STORAGE_KEY);
    if (value === 'en' || value === 'ht' || value === 'fr' || value === 'es' || value === 'pt') {
      return value;
    }
  } catch {
    // Ignore storage access issues and keep the in-memory fallback.
  }

  return null;
}

function writeLanguageToStorage(language: LanguageCode) {
  if (typeof localStorage === 'undefined') {
    return;
  }

  try {
    localStorage.setItem(STORAGE_KEY, language);
  } catch {
    // Ignore storage access issues and keep the in-memory fallback.
  }
}
